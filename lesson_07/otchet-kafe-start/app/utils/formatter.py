"""Текст отчёта: суммы в рублях и заголовки из знаков равенства."""


def format_kopeks(kopeks: int) -> str:
    """Переводит сумму в копейках в строку рублей с запятой.

    Args:
        kopeks: Сумма в копейках. Может быть нулём.

    Returns:
        Строка вида «1 250,00 ₽».
    """
    return f"{kopeks / 100:,.2f} ₽".replace(",", " ").replace(".", ",")


def format_title(text: str, width: int = 40) -> str:
    """Ставит текст по центру строки заданной ширины.

    Args:
        text: Текст заголовка.
        width: Длина строки. Недостающие места заполняются знаком «=».

    Returns:
        Строка заданной длины, текст стоит по центру.
    """
    return text.center(width, "=")
